#!/bin/sh
# Generates /etc/keepalived/keepalived.conf from KEEPALIVED_* variables
# (set with rancher.environment) unless the user provides a complete
# config file, then runs keepalived in the foreground.
set -e

USER_CONFIG=${KEEPALIVED_CONFIG:-/var/lib/rancher/conf/keepalived.conf}
CONFIG=/etc/keepalived/keepalived.conf

# "a, b c" -> one item per line ("a", "b c"); items are separated by commas
# so that a virtual IP can carry options like "10.0.0.100/24 dev eth1".
items() {
    echo "$1" | tr ',' '\n' | sed 's/^[[:space:]]*//; s/[[:space:]]*$//' | grep -v '^$'
}

generate() {
    if [ -z "${KEEPALIVED_VIRTUAL_IPS}" ]; then
        echo "KEEPALIVED_VIRTUAL_IPS is not set and ${USER_CONFIG} does not exist" >&2
        exit 1
    fi

    interface=${KEEPALIVED_INTERFACE:-$(ip -4 route show default | awk '/^default/ { for (i = 1; i <= NF; i++) if ($i == "dev") { print $(i+1); exit } }')}
    if [ -z "${interface}" ]; then
        echo "KEEPALIVED_INTERFACE is not set and no default route was found" >&2
        exit 1
    fi

    state=$(echo "${KEEPALIVED_STATE:-BACKUP}" | tr 'a-z' 'A-Z')
    case "${state}" in
        MASTER|BACKUP) ;;
        *) echo "KEEPALIVED_STATE must be MASTER or BACKUP, got '${state}'" >&2; exit 1 ;;
    esac

    priority=${KEEPALIVED_PRIORITY:-100}
    router_id=${KEEPALIVED_ROUTER_ID:-51}
    advert_int=${KEEPALIVED_ADVERT_INT:-1}
    instance=${KEEPALIVED_INSTANCE:-VI_1}

    {
        echo "# Generated by the BurmillaOS keepalived service from KEEPALIVED_* variables."
        echo "# Write ${USER_CONFIG} to use your own configuration instead."
        echo "global_defs {"
        echo "    router_id ${KEEPALIVED_HOSTNAME:-$(hostname)}"
        if [ -n "${KEEPALIVED_CHECK_SCRIPT}" ]; then
            echo "    enable_script_security"
            echo "    script_user root"
        fi
        echo "}"
        echo
        if [ -n "${KEEPALIVED_CHECK_SCRIPT}" ]; then
            echo "vrrp_script check {"
            echo "    script \"${KEEPALIVED_CHECK_SCRIPT}\""
            echo "    interval ${KEEPALIVED_CHECK_INTERVAL:-5}"
            echo "    timeout ${KEEPALIVED_CHECK_TIMEOUT:-3}"
            echo "    fall ${KEEPALIVED_CHECK_FALL:-2}"
            echo "    rise ${KEEPALIVED_CHECK_RISE:-2}"
            if [ -n "${KEEPALIVED_CHECK_WEIGHT}" ]; then
                echo "    weight ${KEEPALIVED_CHECK_WEIGHT}"
            fi
            echo "}"
            echo
        fi
        echo "vrrp_instance ${instance} {"
        echo "    state ${state}"
        echo "    interface ${interface}"
        echo "    virtual_router_id ${router_id}"
        echo "    priority ${priority}"
        echo "    advert_int ${advert_int}"
        if [ "${KEEPALIVED_NOPREEMPT:-false}" = "true" ]; then
            if [ "${state}" = "BACKUP" ]; then
                echo "    nopreempt"
            else
                echo "KEEPALIVED_NOPREEMPT is ignored with KEEPALIVED_STATE=MASTER, use BACKUP on every node" >&2
            fi
        fi
        if [ -n "${KEEPALIVED_PASSWORD}" ]; then
            echo "    authentication {"
            echo "        auth_type PASS"
            echo "        auth_pass ${KEEPALIVED_PASSWORD}"
            echo "    }"
        fi
        if [ -n "${KEEPALIVED_UNICAST_PEERS}" ]; then
            src_ip=${KEEPALIVED_UNICAST_SRC_IP:-$(ip -4 -o addr show dev "${interface}" scope global | awk '{ sub("/.*", "", $4); print $4; exit }')}
            if [ -n "${src_ip}" ]; then
                echo "    unicast_src_ip ${src_ip}"
            fi
            echo "    unicast_peer {"
            items "${KEEPALIVED_UNICAST_PEERS}" | tr ' ' '\n' | grep -v '^$' | sed 's/^/        /'
            echo "    }"
        fi
        echo "    virtual_ipaddress {"
        items "${KEEPALIVED_VIRTUAL_IPS}" | sed 's/^/        /'
        echo "    }"
        if [ -n "${KEEPALIVED_CHECK_SCRIPT}" ]; then
            echo "    track_script {"
            echo "        check"
            echo "    }"
        fi
        echo "}"
    } > "${CONFIG}"
}

mkdir -p /etc/keepalived
if [ -f "${USER_CONFIG}" ]; then
    echo "Using ${USER_CONFIG}"
    cp "${USER_CONFIG}" "${CONFIG}"
else
    generate
    echo "Generated ${CONFIG}:"
    sed 's/auth_pass .*/auth_pass ********/' "${CONFIG}"
fi
chmod 0600 "${CONFIG}"

# The host /run is shared with the container; remove a stale pid file left
# by a previous instance so keepalived does not refuse to start.
rm -f /run/keepalived.pid /run/vrrp.pid

exec /usr/sbin/keepalived --dont-fork --log-console --use-file "${CONFIG}" "$@"
